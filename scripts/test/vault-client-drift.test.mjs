// vault-client drift test (canonical; copied by sync-vault-client): the vault client in this repository is the canonical one.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

function findRoot() {
  let d = path.dirname(fileURLToPath(import.meta.url));
  let carriesClient = false;
  for (let i = 0; i < 6; i += 1, d = path.dirname(d)) {
    if (fs.existsSync(path.join(d, 'scripts', 'vault-client.hash.json'))) return d;
    // The skill's own assets/scripts copy is not a project copy.
    if (path.basename(d) !== 'assets' && fs.existsSync(path.join(d, 'scripts', 'vault-sync.mjs'))) carriesClient = true;
  }
  // A skill-only repository (AI.Template ships the skill, not a scripts/ copy): nothing to pin, the tests skip.
  if (!carriesClient) return null;
  throw new Error('scripts/vault-client.hash.json not found: run node D:/Git/vault/scripts/sync-vault-client.mjs --apply');
}
const norm = (f) => fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n');
export function clientHash(root) {
  const h = crypto.createHash('sha256');
  h.update(norm(path.join(root, 'scripts', 'vault-sync.mjs')));
  h.update('\n---\n');
  h.update(norm(path.join(root, 'scripts', 'lib', 'vault-gate.mjs')));
  return h.digest('hex');
}

test('scripts/vault-sync.mjs and scripts/lib/vault-gate.mjs are the canonical vault client (hash recorded in scripts/vault-client.hash.json)', (t) => {
  const root = findRoot();
  if (!root) return t.skip('skill-only repository: no scripts/vault-sync.mjs copy to pin');
  const rec = JSON.parse(fs.readFileSync(path.join(root, 'scripts', 'vault-client.hash.json'), 'utf8'));
  assert.equal(clientHash(root), rec.sha256, `the vault client was edited or is stale (recorded version ${rec.version}); never edit it here: refresh with node D:/Git/vault/scripts/sync-vault-client.mjs --apply`);
});

test('when the vault repository is a sibling checkout, the recorded hash equals its canonical hash', (t) => {
  const root = findRoot();
  if (!root) return t.skip('skill-only repository: no scripts/vault-sync.mjs copy to pin');
  const canon = path.resolve(root, '..', 'vault', '.claude', 'skills', 'vault-sync', 'assets', 'scripts');
  if (!fs.existsSync(path.join(canon, 'vault-sync.mjs'))) return t.skip('no sibling vault checkout');
  const h = crypto.createHash('sha256');
  const canonText = norm(path.join(canon, 'vault-sync.mjs'));
  const copy = norm(path.join(root, 'scripts', 'vault-sync.mjs')).replace(/^(#![^\n]*\n)?\/\/ generated by sync-vault-client[^\n]*\n/, '$1');
  assert.equal(copy, canonText, 'scripts/vault-sync.mjs differs from the canonical client (a newer one exists): run sync-vault-client');
  void h;
});
